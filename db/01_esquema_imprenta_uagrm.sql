-- ============================================================================ 

-- BASE DE DATOS: Editorial e Imprenta Universitaria (UAGRM) 

-- Motor: PostgreSQL 16 | Normalización: 3FN (20 tablas) 

-- ============================================================================ 

 

BEGIN; 

 

-- 1. Tabla: rol 

CREATE TABLE rol ( 

    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    nombre VARCHAR(50) NOT NULL UNIQUE, 

    descripcion VARCHAR(255) 

); 

 

-- 2. Tabla: usuario 

CREATE TABLE usuario ( 

    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    rol_id INTEGER NOT NULL REFERENCES rol(id_rol) ON UPDATE CASCADE ON DELETE RESTRICT, 

    nombre_completo VARCHAR(150) NOT NULL, 

    email VARCHAR(120) NOT NULL UNIQUE, 

    password_hash VARCHAR(255) NOT NULL, 

    activo BOOLEAN NOT NULL DEFAULT TRUE, 

    ultimo_acceso TIMESTAMPTZ 

); 

 

-- 3. Tabla: bitacora 

CREATE TABLE bitacora ( 

    id_bitacora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    usuario_id INTEGER NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT, 

    accion VARCHAR(100) NOT NULL, 

    modulo VARCHAR(50) NOT NULL, 

    detalle TEXT, 

    ip_origen VARCHAR(45) NOT NULL, 

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP 

); 

 

-- 4. Tabla: cliente 

CREATE TABLE cliente ( 

    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    tipo_cliente VARCHAR(30) NOT NULL, 

    razon_social VARCHAR(150) NOT NULL, 

    telefono VARCHAR(30), 

    email VARCHAR(120), 

    direccion VARCHAR(200), 

    codigo_facultad VARCHAR(20), 

    dependencia VARCHAR(100), 

    ci_nit VARCHAR(30) 

); 

 

-- 5. Tabla: categoria_insumo 

CREATE TABLE categoria_insumo ( 

    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    nombre VARCHAR(80) NOT NULL UNIQUE, 

    unidad_base VARCHAR(30) NOT NULL 

); 

 

-- 6. Tabla: insumo 

CREATE TABLE insumo ( 

    id_insumo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    categoria_id INTEGER NOT NULL REFERENCES categoria_insumo(id_categoria) ON UPDATE CASCADE ON DELETE RESTRICT, 

    codigo VARCHAR(30) NOT NULL UNIQUE, 

    descripcion VARCHAR(150) NOT NULL, 

    stock_actual NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    stock_minimo NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    costo_reposicion NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    unidad_medida VARCHAR(30) NOT NULL 

); 

 

-- 7. Tabla: proveedor 

CREATE TABLE proveedor ( 

    id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    razon_social VARCHAR(150) NOT NULL, 

    nit VARCHAR(30) NOT NULL UNIQUE, 

    contacto VARCHAR(100), 

    telefono VARCHAR(30), 

    email VARCHAR(120), 

    direccion VARCHAR(200) 

); 

 

-- 8. Tabla: insumo_proveedor 

CREATE TABLE insumo_proveedor ( 

    insumo_id INTEGER NOT NULL REFERENCES insumo(id_insumo) ON UPDATE CASCADE ON DELETE RESTRICT, 

    proveedor_id INTEGER NOT NULL REFERENCES proveedor(id_proveedor) ON UPDATE CASCADE ON DELETE RESTRICT, 

    precio_cotizado NUMERIC(12,2) NOT NULL, 

    fecha_cotizacion DATE NOT NULL DEFAULT CURRENT_DATE, 

    PRIMARY KEY (insumo_id, proveedor_id) 

); 

 

-- 9. Tabla: tarifa 

CREATE TABLE tarifa ( 

    id_tarifa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    concepto VARCHAR(100) NOT NULL, 

    precio_unitario NUMERIC(12,2) NOT NULL, 

    tipo_tarifa VARCHAR(50) NOT NULL, 

    vigencia_hasta DATE NOT NULL 

); 

 

-- 10. Tabla: movimiento_inventario 

CREATE TABLE movimiento_inventario ( 

    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    insumo_id INTEGER NOT NULL REFERENCES insumo(id_insumo) ON UPDATE CASCADE ON DELETE RESTRICT, 

    usuario_id INTEGER NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT, 

    tipo_movimiento VARCHAR(40) NOT NULL, 

    cantidad NUMERIC(12,2) NOT NULL, 

    saldo_resultante NUMERIC(12,2) NOT NULL, 

    referencia VARCHAR(100), 

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP 

); 

 

-- 11. Tabla: tipo_trabajo 

CREATE TABLE tipo_trabajo ( 

    id_tipo_trabajo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    nombre VARCHAR(80) NOT NULL UNIQUE, 

    descripcion VARCHAR(255), 

    activo BOOLEAN NOT NULL DEFAULT TRUE 

); 

 

-- 12. Tabla: proforma 

CREATE TABLE proforma ( 

    id_proforma INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    cliente_id INTEGER NOT NULL REFERENCES cliente(id_cliente) ON UPDATE CASCADE ON DELETE RESTRICT, 

    usuario_id INTEGER NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT, 

    codigo_proforma VARCHAR(30) NOT NULL UNIQUE, 

    modalidad VARCHAR(50) NOT NULL, 

    total_presupuesto NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    estado VARCHAR(30) NOT NULL DEFAULT 'EMITIDA', 

    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, 

    fecha_vencimiento DATE NOT NULL 

); 

 

-- 13. Tabla: detalle_proforma 

CREATE TABLE detalle_proforma ( 

    id_detalle_proforma INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    proforma_id INTEGER NOT NULL REFERENCES proforma(id_proforma) ON UPDATE CASCADE ON DELETE CASCADE, 

    tipo_trabajo_id INTEGER NOT NULL REFERENCES tipo_trabajo(id_tipo_trabajo) ON UPDATE CASCADE ON DELETE RESTRICT, 

    insumo_id INTEGER REFERENCES insumo(id_insumo) ON UPDATE CASCADE ON DELETE RESTRICT, 

    tarifa_id INTEGER REFERENCES tarifa(id_tarifa) ON UPDATE CASCADE ON DELETE RESTRICT, 

    descripcion_trabajo VARCHAR(200) NOT NULL, 

    tiraje INTEGER NOT NULL, 

    paginas_totales INTEGER NOT NULL, 

    costo_papel NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    costo_tinta NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    costo_planchas NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    costo_mano_obra NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    subtotal NUMERIC(12,2) NOT NULL 

); 

 

-- 14. Tabla: orden_trabajo 

CREATE TABLE orden_trabajo ( 

    id_orden INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    proforma_id INTEGER NOT NULL UNIQUE REFERENCES proforma(id_proforma) ON UPDATE CASCADE ON DELETE RESTRICT, 

    usuario_id INTEGER NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT, 

    codigo_ot VARCHAR(30) NOT NULL UNIQUE, 

    fecha_compromiso DATE NOT NULL, 

    prioridad VARCHAR(20) NOT NULL DEFAULT 'NORMAL', 

    estado_actual VARCHAR(30) NOT NULL DEFAULT 'REGISTRADO', 

    observaciones TEXT, 

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP 

); 

 

-- 15. Tabla: detalle_orden 

CREATE TABLE detalle_orden ( 

    id_detalle_orden INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    orden_id INTEGER NOT NULL REFERENCES orden_trabajo(id_orden) ON UPDATE CASCADE ON DELETE CASCADE, 

    formato_corte VARCHAR(50) NOT NULL, 

    tipo_encuadernacion VARCHAR(80) NOT NULL, 

    especificaciones_taller TEXT 

); 

 

-- 16. Tabla: historial_estado 

CREATE TABLE historial_estado ( 

    id_historial INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    orden_id INTEGER NOT NULL REFERENCES orden_trabajo(id_orden) ON UPDATE CASCADE ON DELETE CASCADE, 

    usuario_id INTEGER NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT, 

    estado_anterior VARCHAR(30) NOT NULL, 

    estado_nuevo VARCHAR(30) NOT NULL, 

    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP 

); 

 

-- 17. Tabla: consumo_real 

CREATE TABLE consumo_real ( 

    id_consumo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    orden_id INTEGER NOT NULL REFERENCES orden_trabajo(id_orden) ON UPDATE CASCADE ON DELETE RESTRICT, 

    insumo_id INTEGER NOT NULL REFERENCES insumo(id_insumo) ON UPDATE CASCADE ON DELETE RESTRICT, 

    cantidad_utilizada NUMERIC(12,2) NOT NULL, 

    cantidad_merma NUMERIC(12,2) NOT NULL DEFAULT 0.00, 

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP 

); 

 

-- 18. Tabla: periodo_academico 

CREATE TABLE periodo_academico ( 

    id_periodo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    gestion INTEGER NOT NULL, 

    semestre VARCHAR(20) NOT NULL, 

    fecha_inicio DATE NOT NULL, 

    fecha_fin DATE NOT NULL, 

    es_pico_demanda BOOLEAN NOT NULL DEFAULT FALSE 

); 

 

-- 19. Tabla: prediccion_demanda 

CREATE TABLE prediccion_demanda ( 

    id_prediccion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    insumo_id INTEGER NOT NULL REFERENCES insumo(id_insumo) ON UPDATE CASCADE ON DELETE RESTRICT, 

    periodo_id INTEGER NOT NULL REFERENCES periodo_academico(id_periodo) ON UPDATE CASCADE ON DELETE RESTRICT, 

    cantidad_proyectada NUMERIC(12,2) NOT NULL, 

    margen_variabilidad NUMERIC(12,2) NOT NULL, 

    stock_sugerido_compra NUMERIC(12,2) NOT NULL, 

    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP 

); 

 

-- 20. Tabla: orden_compra 

CREATE TABLE orden_compra ( 

    id_orden_compra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    proveedor_id INTEGER NOT NULL REFERENCES proveedor(id_proveedor) ON UPDATE CASCADE ON DELETE RESTRICT, 

    prediccion_id INTEGER REFERENCES prediccion_demanda(id_prediccion) ON UPDATE CASCADE ON DELETE SET NULL, 

    total_estimado NUMERIC(12,2) NOT NULL, 

    fecha_generacion DATE NOT NULL DEFAULT CURRENT_DATE, 

    estado VARCHAR(30) NOT NULL DEFAULT 'SUGERIDA' 

); 

-- ============================================================= 

-- INDICES PARA OPTIMIZACION DE BUSQUEDAS Y REPORTES 

-- ============================================================= 

CREATE INDEX idx_usuario_rol ON usuario(rol_id); 

CREATE INDEX idx_bitacora_fecha ON bitacora(created_at); 

CREATE INDEX idx_bitacora_usuario ON bitacora(usuario_id); 

CREATE INDEX idx_insumo_categoria ON insumo(categoria_id); 

CREATE INDEX idx_insumo_prov_proveedor ON insumo_proveedor(proveedor_id); 

CREATE INDEX idx_movimiento_insumo ON movimiento_inventario(insumo_id, created_at); 

CREATE INDEX idx_movimiento_usuario ON movimiento_inventario(usuario_id); 

CREATE INDEX idx_proforma_cliente ON proforma(cliente_id); 

CREATE INDEX idx_proforma_usuario ON proforma(usuario_id); 

CREATE INDEX idx_detalle_proforma_prof ON detalle_proforma(proforma_id); 

CREATE INDEX idx_detalle_proforma_tipo ON detalle_proforma(tipo_trabajo_id); 

CREATE INDEX idx_detalle_proforma_insumo ON detalle_proforma(insumo_id); 

CREATE INDEX idx_detalle_proforma_tarifa ON detalle_proforma(tarifa_id); 

CREATE INDEX idx_orden_usuario ON orden_trabajo(usuario_id); 

CREATE INDEX idx_detalle_orden_orden ON detalle_orden(orden_id); 

CREATE INDEX idx_historial_orden ON historial_estado(orden_id, fecha_cambio); 

CREATE INDEX idx_historial_usuario ON historial_estado(usuario_id); 

CREATE INDEX idx_consumo_orden_insumo ON consumo_real(orden_id, insumo_id); 

CREATE INDEX idx_consumo_insumo ON consumo_real(insumo_id); 

CREATE INDEX idx_prediccion_insumo_periodo ON prediccion_demanda(insumo_id, periodo_id); 

CREATE INDEX idx_prediccion_periodo ON prediccion_demanda(periodo_id); 

CREATE INDEX idx_orden_compra_proveedor ON orden_compra(proveedor_id); 

CREATE INDEX idx_orden_compra_prediccion ON orden_compra(prediccion_id); 

 

COMMIT; 